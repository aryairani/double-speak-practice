#!/usr/bin/env python3
"""Synthesize story audio with Piper and emit stories.js for the web app.

Usage:
    python3 tools/build_audio.py --voices-dir /path/to/voices [--only marisol,priya] [--force]

Expects piper voice directories (as distributed in the sherpa-onnx "tts-models" GitHub release):
    <voices-dir>/vits-piper-en_US-lessac-medium/en_US-lessac-medium.onnx (+ .onnx.json)
    <voices-dir>/vits-piper-en_US-ryan-medium/en_US-ryan-medium.onnx   (+ .onnx.json)

Outputs:
    audio/<story-id>-<voice>.mp3     mono 22.05 kHz MP3 of the story text
    audio/check-left-<voice>.mp3 ... short "left ear / right ear" headphone-check clips
    stories.js                       window.STORIES / window.VOICES for the app (no fetch needed)
"""
import argparse, json, os, subprocess, sys, tempfile, wave

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VOICES = {
    "lessac": {"dir": "vits-piper-en_US-lessac-medium", "model": "en_US-lessac-medium.onnx", "label": "Lessac (female)"},
    "ryan":   {"dir": "vits-piper-en_US-ryan-medium",   "model": "en_US-ryan-medium.onnx",   "label": "Ryan (male)"},
}
CHECK_CLIPS = {
    "check-left": "This is your left ear. The first story will play here.",
    "check-right": "This is your right ear. The second story will play here.",
}


def synth(voice, text, out_mp3, length_scale):
    from piper import SynthesisConfig
    with tempfile.NamedTemporaryFile(suffix=".wav", delete=False) as tmp:
        wav_path = tmp.name
    try:
        with wave.open(wav_path, "wb") as w:
            voice.synthesize_wav(text, w, syn_config=SynthesisConfig(length_scale=length_scale))
        subprocess.run(
            ["ffmpeg", "-y", "-loglevel", "error", "-i", wav_path,
             "-codec:a", "libmp3lame", "-b:a", "48k", "-ac", "1", "-ar", "22050", out_mp3],
            check=True,
        )
    finally:
        os.unlink(wav_path)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--voices-dir", required=True)
    ap.add_argument("--only", default="")
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--length-scale", type=float, default=1.0, help="piper speaking rate (1.0 = normal, >1 slower)")
    args = ap.parse_args()

    from piper import PiperVoice

    stories = json.load(open(os.path.join(ROOT, "data", "stories.json"), encoding="utf-8"))
    only = {s for s in args.only.split(",") if s}
    audio_dir = os.path.join(ROOT, "audio")
    os.makedirs(audio_dir, exist_ok=True)

    for vname, v in VOICES.items():
        model = os.path.join(args.voices_dir, v["dir"], v["model"])
        if not os.path.exists(model):
            sys.exit(f"missing voice model {model}")
        print(f"loading {vname}", flush=True)
        voice = PiperVoice.load(model)
        jobs = [(f"{k}-{vname}", t) for k, t in CHECK_CLIPS.items()]
        jobs += [(f"{s['id']}-{vname}", s["text"]) for s in stories if not only or s["id"] in only]
        for name, text in jobs:
            out = os.path.join(audio_dir, name + ".mp3")
            if os.path.exists(out) and not args.force:
                continue
            print(f"  {name}", flush=True)
            synth(voice, text, out, args.length_scale)

    payload = {
        "stories": stories,
        "voices": {k: v["label"] for k, v in VOICES.items()},
    }
    with open(os.path.join(ROOT, "stories.js"), "w", encoding="utf-8") as f:
        f.write("// Generated by tools/build_audio.py from data/stories.json. Do not edit by hand.\n")
        f.write("window.STORIES = " + json.dumps(payload["stories"], ensure_ascii=False) + ";\n")
        f.write("window.VOICES = " + json.dumps(payload["voices"], ensure_ascii=False) + ";\n")
    print("wrote stories.js")


if __name__ == "__main__":
    main()
